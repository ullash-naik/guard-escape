#include "maze.h"
#include <stdlib.h>

void maze_generate(Maze *m, int loops)
{
    /* Array used as a STACK. Top of stack = current cell being carved. */
    Cell stack[MAZE_W * MAZE_H];
    int top = 0;

    /* Start with everything as wall. */
    for (int y = 0; y < MAZE_H; y++)
        for (int x = 0; x < MAZE_W; x++)
            m->grid[y][x] = TILE_WALL;

    m->grid[1][1] = TILE_FLOOR;
    stack[top++] = (Cell){ 1, 1 };                 /* push */

    while (top > 0) {
        Cell c = stack[top - 1];                   /* peek */

        /* Find unvisited neighbours two cells away. */
        int dirs[4], n = 0;
        for (int d = 0; d < 4; d++) {
            int nx = c.x + DIR_X[d] * 2;
            int ny = c.y + DIR_Y[d] * 2;
            if (nx > 0 && nx < MAZE_W - 1 && ny > 0 && ny < MAZE_H - 1 &&
                m->grid[ny][nx] == TILE_WALL)
                dirs[n++] = d;
        }

        if (n == 0) {                              /* dead end: backtrack */
            top--;                                 /* pop */
            continue;
        }

        int d = dirs[rand() % n];
        m->grid[c.y + DIR_Y[d]][c.x + DIR_X[d]] = TILE_FLOOR;         /* wall between */
        m->grid[c.y + DIR_Y[d] * 2][c.x + DIR_X[d] * 2] = TILE_FLOOR; /* next cell */
        stack[top++] = (Cell){ c.x + DIR_X[d] * 2, c.y + DIR_Y[d] * 2 }; /* push */
    }

    /* Open extra walls to create loops (escape routes). */
    int made = 0, tries = 0;
    while (made < loops && tries < loops * 60) {
        tries++;
        int x = 1 + rand() % (MAZE_W - 2);
        int y = 1 + rand() % (MAZE_H - 2);
        if (m->grid[y][x] != TILE_WALL)
            continue;

        int betweenLeftRight = (x % 2 == 0 && y % 2 == 1) &&
                               m->grid[y][x - 1] == TILE_FLOOR &&
                               m->grid[y][x + 1] == TILE_FLOOR;
        int betweenUpDown    = (x % 2 == 1 && y % 2 == 0) &&
                               m->grid[y - 1][x] == TILE_FLOOR &&
                               m->grid[y + 1][x] == TILE_FLOOR;

        if (betweenLeftRight || betweenUpDown) {
            m->grid[y][x] = TILE_FLOOR;
            made++;
        }
    }
}

int maze_walkable(const Maze *m, int x, int y)
{
    return x >= 0 && x < MAZE_W && y >= 0 && y < MAZE_H &&
           m->grid[y][x] == TILE_FLOOR;
}

