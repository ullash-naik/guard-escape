int maze_load_preset(Maze *m, int index)
{
    if (index < 0 || index >= MAZE_PRESET_COUNT)
        return 0;
    for (int y = 0; y < MAZE_H; y++)
        for (int x = 0; x < MAZE_W; x++)
            m->grid[y][x] = PRESETS[index][y][x] == '#' ? TILE_WALL : TILE_FLOOR;
    return 1;
}
